def digest_rows(cursor):
    digest = hashlib.sha256()
    count = 0
    while rows := cursor.fetchmany(1000):
        for row in rows:
            digest.update(json.dumps(row, ensure_ascii=False, separators=(",", ":"), allow_nan=False).encode("utf-8"))
            digest.update(b"\n")
            count += 1
    return count, digest.hexdigest()


def validate_source(path: Path):
    resolved = path.resolve(strict=True)
    forbidden = Path("/var/lib/salom-api/directory.sqlite3").resolve()
    if resolved == forbidden or (forbidden.exists() and resolved.samefile(forbidden)):
        raise ValueError("Pass a consistent backup file, never the live production database")
    uri = resolved.as_uri() + "?mode=ro"
    db = sqlite3.connect(uri, uri=True)
    db.execute("PRAGMA query_only=ON")
    integrity = db.execute("PRAGMA integrity_check").fetchone()[0]
    if integrity != "ok":
        db.close()
        raise ValueError(f"SQLite integrity check failed: {integrity}")
    found_tables = {row[0] for row in db.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'")}
    expected_tables = set(TABLES)
    optional_tables = {"call_sessions", "call_push_jobs"}
    if found_tables - expected_tables or expected_tables - found_tables - optional_tables:
        db.close()
        raise ValueError("Unexpected SQLite table set; refusing to omit or invent user data")
    if ("call_sessions" in found_tables) != ("call_push_jobs" in found_tables):
        db.close()
        raise ValueError("Incomplete call schema in SQLite source; refusing an inconsistent migration")
    for table, columns in TABLES.items():
        if table not in found_tables:
            continue
        found = tuple(row[1] for row in db.execute(f"PRAGMA table_info({table})"))
        if set(found) != set(columns):
            db.close()
            raise ValueError(f"Unexpected SQLite columns for {table}; refusing to omit or invent fields")
    return db, found_tables


def migrate(source_path: Path, dsn: str):
    source, source_tables = validate_source(source_path)
    target = psycopg.connect(dsn)
    try:
        with target.transaction():
            database_name = target.execute("SELECT current_database()").fetchone()[0].lower()
            if not database_name.endswith(("_test", "_qa")):
                raise ValueError("Target database name must end in '_test' or '_qa'; production migration is disabled")
            existing = target.execute("SELECT to_regclass('public.profiles')").fetchone()[0]
            if existing is not None:
                raise ValueError("Target already contains Salom tables; the rehearsal refuses to overwrite it")
            for statement in DDL.strip().split(";\n"):
                if statement.strip():
                    target.execute(statement)
            for table, columns in TABLES.items():
                quoted_columns = ",".join(f'"{name}"' for name in columns)
                ordering = ",".join(f'"{name}"' for name in ORDER_COLUMNS[table])
                source_cursor = source.execute(f'SELECT {quoted_columns} FROM "{table}" ORDER BY {ordering}') if table in source_tables else None
                insert = f'INSERT INTO "{table}" ({quoted_columns}) VALUES ({",".join("%s" for _ in columns)})'
                while source_cursor is not None and (rows := source_cursor.fetchmany(1000)):
                    with target.cursor() as cursor:
                        cursor.executemany(insert, rows)

            for table in ("messages", "message_events"):
                target.execute(
                    f"SELECT setval(pg_get_serial_sequence('{table}','id'), COALESCE(MAX(id),1), MAX(id) IS NOT NULL) FROM {table}"
                )

            report = {}
            for table, columns in TABLES.items():
                quoted_columns = ",".join(f'"{name}"' for name in columns)
                ordering = ",".join(f'"{name}"' for name in ORDER_COLUMNS[table])
                source_result = digest_rows(source.execute(f'SELECT {quoted_columns} FROM "{table}" ORDER BY {ordering}')) if table in source_tables else (0, hashlib.sha256().hexdigest())
                target_result = digest_rows(target.execute(f'SELECT {quoted_columns} FROM "{table}" ORDER BY {ordering}'))
                if source_result != target_result:
                    raise ValueError(f"Count/checksum mismatch for {table}")
                report[table] = {"rows": source_result[0], "sha256": source_result[1]}
        return report
    finally:
        target.close()
        source.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path, help="Path to a consistent SQLite backup")
    args = parser.parse_args()
    dsn = os.environ.get("SALOM_PG_TEST_DSN", "")
    if not dsn:
        parser.error("Set SALOM_PG_TEST_DSN to a disposable PostgreSQL test database; credentials are never printed")
    try:
        print(json.dumps(migrate(args.source, dsn), indent=2))
    except Exception as error:
        print(f"Migration rehearsal failed: {type(error).__name__}: {error}", file=sys.stderr)
        raise SystemExit(1)


if __name__ == "__main__":
    main()
